use super::ResourceRef;
use serde::{Deserialize, Serialize};

#[derive(Clone, Debug, Serialize, Deserialize, PartialEq, Eq)]
#[serde(rename_all = "snake_case")]
pub enum ReviewKind {
    Action,
    Yaml,
    Batch,
}
#[derive(Clone, Debug, Serialize, Deserialize, PartialEq, Eq, PartialOrd, Ord)]
#[serde(rename_all = "snake_case")]
pub enum ReviewWarning {
    Dependents,
    CrdDeletion,
    NamespaceDeletion,
    PodDisruptionBudget,
    ArgoPrune,
}
#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct ReviewStep {
    pub operation: String,
    pub resource: ResourceRef,
    pub summary: String,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub diff: Option<String>,
}
/// Display data is generated by the backend from the prepared, immutable operation.
/// The renderer never infers semantics from human-readable review text.
#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct MutationReview {
    pub kind: ReviewKind,
    pub steps: Vec<ReviewStep>,
    pub warnings: Vec<ReviewWarning>,
}
impl MutationReview {
    pub fn single(
        kind: ReviewKind,
        operation: &str,
        resource: &ResourceRef,
        summary: String,
        diff: Option<String>,
        warnings: Vec<ReviewWarning>,
    ) -> Self {
        Self {
            kind,
            steps: vec![ReviewStep {
                operation: operation.into(),
                resource: resource.clone(),
                summary,
                diff,
            }],
            warnings,
        }
    }
}
